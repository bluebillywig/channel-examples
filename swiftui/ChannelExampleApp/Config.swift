import Foundation

let DEV_MODE = false
let CDN_DEV_BUNDLE_URL = "https://cdn.bluebillywig.com/apps/channel/latest/channel-native.js"

func getBundleUrl(env: Environment, customUrl: String?) -> String {
    if let url = customUrl, !url.isEmpty { return url }
    if DEV_MODE { return "https://cdn.bluebillywig.com/apps/channel/latest/channel-native.js" }
    if env == .dev { return CDN_DEV_BUNDLE_URL }
    let host = env == .prod ? "cdn.bluebillywig.com" : "cdn-\(env.rawValue).bluebillywig.com"
    return "https://\(host)/apps/channel/latest/channel-native.js"
}

func getChannelUrl(host: String, id: String) -> String {
    "https://\(host)/ch/\(id).json"
}

